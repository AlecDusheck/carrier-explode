export type IconName = keyof typeof ICONS;

export const ICON_SIZE = 12;

const drawn = (rows: readonly string[]): PixelPath[] =>
	pixelPaths(rows, Object.fromEntries([...new Set(rows.join(""))].filter(isInk).map((c) => [c, PALETTE[c]])));

const cache = new Map<IconName, readonly PixelPath[]>();

export function iconPaths(name: IconName): readonly PixelPath[] {
	let paths = cache.get(name);
	if (!paths) cache.set(name, (paths = drawn(ICONS[name])));
	return paths;
}

const svgUrl = (paths: readonly PixelPath[], size: number): string =>
	`url("data:image/svg+xml,${encodeURIComponent(
		`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges">${paths
			.map((p) => `<path fill="${p.fill}" d="${p.d}"/>`)
			.join("")}</svg>`,
	)}")`;

const urls = new Map<IconName, string>();

/** An icon as a CSS image: a matrix cell paints it rather than holding an SVG of its own. */
export function iconUrl(name: IconName): string {
	let url = urls.get(name);
	if (!url) urls.set(name, (url = svgUrl(iconPaths(name), ICON_SIZE)));
	return url;
}

