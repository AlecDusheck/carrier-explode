/** 12-pixel icons drawn as the favicon is: one path per colour, a unit square per pixel. */

const PALETTE = {
	k: "#16130f",
	d: "#55514a",
	g: "#9a958a",
	w: "#ffffff",
	b: "#3a5a80",
	l: "#6f8fb5",
	y: "#e0b030",
	r: "#c8361e",
	n: "#3f8a3a",
} as const;
type Ink = keyof typeof PALETTE;
const isInk = (c: string): c is Ink => c in PALETTE;

export interface PixelPath {
	readonly fill: string;
	readonly d: string;
}

/** Each row's runs of one ink become one rectangle; `.` is clear. */
function pixelPaths(rows: readonly string[], palette: Readonly<Record<string, string>>): PixelPath[] {
	const byFill = new Map<string, string[]>();
	rows.forEach((row, y) => {
		for (let x = 0; x < row.length;) {
			const c = row.charAt(x);
			let end = x + 1;
			while (row.charAt(end) === c) end++;
			const fill = palette[c];
			if (fill !== undefined) {
				const runs = byFill.get(fill) ?? [];
				runs.push(`M${x} ${y}h${end - x}v1h-${end - x}z`);
				byFill.set(fill, runs);
			}
			x = end;
		}
	});
	return [...byFill].map(([fill, runs]) => ({ fill, d: runs.join("") }));
}

